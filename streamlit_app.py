import streamlit as st
import pandas as pd
import numpy as np
import joblib
import matplotlib.pyplot as plt
import shap
from fpdf import FPDF
import datetime

# Page configuration 
st.set_page_config(page_title="Maternal Health Risk Classifier", page_icon="🏥", layout="centered")

# ==============================================================================
# LOAD THE TRAINED PIPELINE
# ==============================================================================
@st.cache_resource
def load_pipeline():
    return joblib.load('elite_medical_rf_model.joblib')

try:
    pipeline = load_pipeline()
    scaler = pipeline['scaler']
    rf_model = pipeline['classifier']
    feature_names = list(pipeline.feature_names_in_)
except FileNotFoundError:
    st.error("⚠️ Error:'elite_medical_rf_model.joblib' not found ")
    st.stop()

# ==============================================================================
# WEB APPLICATION INTERFACE LAYOUT
# ==============================================================================
st.title("Maternal Health Risk Classifier")
st.markdown("Enter a patient's current vital signs below to instantly calculate their risk level along with a risk contribution analysis.")


# Input Fields 
st.subheader("Patient Vital Signs Input")
col1, col2 = st.columns(2)

with col1:
    age = st.slider("Patient Age (Years)", min_value=1, max_value=100, value=45)
    systolic_bp = st.slider("Systolic Blood Pressure (mmHg)", min_value=70, max_value=220, value=120)
    heart_rate = st.slider("Heart Rate (BPM)", min_value=40, max_value=180, value=75)

with col2:
    diastolic_bp = st.slider("Diastolic Blood Pressure (mmHg)", min_value=40, max_value=120, value=80)
    bs = st.slider("Blood Sugar / Blood Glucose (mmol/L)", min_value=3.0, max_value=20.0, value=5.5, step=0.1)
    body_temp = st.slider("Body Temperature (°F)", min_value=95.0, max_value=106.0, value=98.6, step=0.1)

# Assemble inputs into a raw data vector
raw_input_df = pd.DataFrame([{
    'Age': age,
    'SystolicBP': systolic_bp,
    'DiastolicBP': diastolic_bp,
    'BS': bs,
    'BodyTemp': body_temp,
    'HeartRate': heart_rate
}])

# ==============================================================================
# COMPUTE LIVE RISK DIAGNOSIS
# ==============================================================================
# Scale inputs to match scaled trained model
scaled_input_df = scaler.transform(raw_input_df[feature_names])

# Get probability array across classes [Low, Mid, High]
pred_probabilities = rf_model.predict_proba(scaled_input_df)[0]
predicted_class = np.argmax(pred_probabilities)

# Map numeric classifications 
labels = {0: ("🟢 LOW RISK", "Patient is stable. Schedule standard diagnostic follow-ups."),
          1: ("🟡 MID RISK", "Patient requires monitoring. Flag for closer clinical observation."),
          2: ("🚨 HIGH RISK", "Recommend urgent clinical assessment")}

status_title, status_desc = labels[predicted_class]

# Display the Triage Verdict box 
st.subheader("🩺 Real-Time Diagnostic Verdict")
if predicted_class == 0:
    st.success(f"**{status_title}** — {status_desc}")
elif predicted_class == 1:
    st.warning(f"**{status_title}** — {status_desc}")
else:
    st.error(f"**{status_title}** — {status_desc}")

# Display percentage chips
p_low, p_mid, p_high = pred_probabilities
st.write(f"**Confidence Metrics:** Low Risk: `{p_low*100:.1f}%` | Mid Risk: `{p_mid*100:.1f}%` | High Risk: `{p_high*100:.1f}%` ")


st.warning("This prediction is generated by a machine learning model trained on synthetic data and is intended for educational purposes only. It should not be used as a substitute for professional medical diagnosis or treatment")


# ==============================================================================
#  EXPLAINABLE AI AUDIT GRAPH
# ==============================================================================

st.subheader("🛡️ Clinical Risk Contribution Analysis")
st.markdown("This chart shows how each health measurement influenced the model's assessment of High Risk. Bars extending to the right indicate measurements that increased the likelihood of a High Risk prediction, while bars extending to the left indicate measurements that reduced it. Longer bars represent a greater influence on the model's assessment.")
# Initialize the real SHAP engine on your model
explainer = shap.TreeExplainer(rf_model)

# Calculate the real SHAP values 
shap_values = explainer.shap_values(scaled_input_df)

if isinstance(shap_values, list):
    # Older SHAP version handler (list of arrays)
    real_contributions = shap_values[predicted_class][0]
else:
    # Newer SHAP version handler (3D array: rows, features, classes)
    HIGH_RISK_CLASS = 2
    real_contributions = shap_values[0, :, HIGH_RISK_CLASS]

# Convert array to a standard list for the plotting code below
tree_contributions = real_contributions.tolist()

# Create the visual plot
fig, ax = plt.subplots(figsize=(8, 3))

# Ensure tree_contributions matches the exact length of your features

clean_contributions = np.array(tree_contributions).flatten()

# Assign colors: Red for risk escalators (>0), Green for safe pullers (<=0)
colors = ['#ff4b4b' if x > 0 else '#23c14c' for x in clean_contributions]

# Draw the horizontal bars safely
y_pos = np.arange(len(feature_names))
ax.barh(y_pos, clean_contributions, color=colors, edgecolor='none', height=0.6)

# Set a symmetric x-axis around zero
max_abs = np.max(np.abs(clean_contributions))
ax.set_xlim(-max_abs * 1.1, max_abs * 1.1)

# Attach clear y-axis labels
ax.set_yticks(y_pos)
ax.set_yticklabels(feature_names, fontsize=10, fontweight='bold')
ax.invert_yaxis()

# Style clean-up
ax.axvline(x=0, color='#31333F', linestyle='-', linewidth=1, alpha=0.5)
ax.spines['top'].set_visible(False)
ax.spines['right'].set_visible(False)
ax.spines['left'].set_visible(False)
ax.spines['bottom'].set_visible(False)
ax.set_xlabel("<- Reduces High Risk  |  Increases High Risk ->", fontsize=9, color='#31333F')

# Render the plot inside the web window frame cleanly
st.pyplot(fig)

# ==============================================================================
# CLINICAL NOTES & PDF REPORT DOWNLOAD ENGINE
# ==============================================================================

st.subheader("Clinical Consultation Notes")


def generate_pdf(patient_data, probabilities, diagnosis, notes):
    """
    Generate a clinical PDF report in memory.
    """

    pdf = FPDF()
    pdf.add_page()

    # --------------------------------------------------------------------------
    # Header
    # --------------------------------------------------------------------------

    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(49, 51, 63)

    pdf.cell(
        0,
        10,
        "MATERNAL HEALTH RISK PREDICTOR REPORT",
        ln=True,
        align="C"
    )

    pdf.set_font("Helvetica", "I", 10)
    pdf.set_text_color(100, 100, 100)

    current_date = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    pdf.cell(
        0,
        8,
        f"Generated on: {current_date}",
        ln=True,
        align="C"
    )

    pdf.ln(5)

    # Header divider
    pdf.line(
        10,
        pdf.get_y(),
        200,
        pdf.get_y()
    )

    pdf.ln(6)

    # --------------------------------------------------------------------------
    # 1. Patient Vital Signs Summary
    # --------------------------------------------------------------------------

    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(49, 51, 63)

    pdf.cell(
        0,
        8,
        "1. Patient Vital Signs Summary",
        ln=True
    )

    pdf.ln(2)

    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(0, 0, 0)

    for key, value in patient_data.items():

        pdf.cell(
            75,
            7,
            f"{key}:",
            border=0
        )

        pdf.cell(
            0,
            7,
            str(value),
            border=0,
            ln=True
        )

    pdf.ln(5)

    # --------------------------------------------------------------------------
    # 2. AI Triage Diagnostic Verdict
    # --------------------------------------------------------------------------

    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(49, 51, 63)

    pdf.cell(
        0,
        8,
        "2. AI Triage Diagnostic Verdict",
        ln=True
    )

    pdf.ln(2)

    # Diagnosis
    pdf.set_font("Helvetica", "B", 11)

    if "HIGH" in diagnosis.upper():
        pdf.set_text_color(197, 15, 15)

    elif "MID" in diagnosis.upper() or "MEDIUM" in diagnosis.upper():
        pdf.set_text_color(180, 110, 0)

    else:
        pdf.set_text_color(15, 117, 43)

    pdf.cell(
        0,
        8,
        f"Assigned Risk Tier: {diagnosis}",
        ln=True
    )

    # Confidence scores
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 100, 100)

    p_low, p_mid, p_high = probabilities

    pdf.cell(
        0,
        6,
        (
            f"Confidence Breakdown: "
            f"Low {p_low * 100:.1f}% | "
            f"Mid {p_mid * 100:.1f}% | "
            f"High {p_high * 100:.1f}%"
        ),
        ln=True
    )

    pdf.ln(5)

    # --------------------------------------------------------------------------
    # 3. Clinical Consultation Notes
    # --------------------------------------------------------------------------

    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(49, 51, 63)

    pdf.cell(
        0,
        8,
        "3. Clinical Consultation Notes",
        ln=True
    )

    pdf.ln(2)

    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(0, 0, 0)

    if not notes.strip():
        notes = "No consultation notes entered."

    # Use multi_cell so long notes wrap correctly.
    pdf.multi_cell(
        0,
        6,
        notes,
        border=1
    )

    pdf.ln(15)

    # --------------------------------------------------------------------------
    # Clinician Signature
    # --------------------------------------------------------------------------

    pdf.line(
        10,
        pdf.get_y(),
        80,
        pdf.get_y()
    )

    pdf.ln(2)

    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(120, 120, 120)

    pdf.cell(
        0,
        5,
        "Attending Clinician Signature",
        ln=True
    )

    pdf.ln(8)

    # --------------------------------------------------------------------------
    # Disclaimer
    # --------------------------------------------------------------------------

    pdf.line(
        10,
        pdf.get_y(),
        200,
        pdf.get_y()
    )

    pdf.ln(3)

    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(120, 120, 120)

    disclaimer = (
        "This report contains predictions generated by a machine learning "
        "model trained on maternal health data. The prediction is intended "
        "for educational and research purposes and should not be used as "
        "a substitute for professional medical diagnosis or treatment."
    )

    pdf.multi_cell(
        0,
        5,
        disclaimer
    )

    # --------------------------------------------------------------------------
    # Return PDF as bytes
    # --------------------------------------------------------------------------

    return bytes(pdf.output())


# ==============================================================================
# CLINICAL NOTES INPUT
# ==============================================================================

doctor_notes = st.text_area(
    "Enter diagnostic notes, prescription steps, or patient tracking details:",
    placeholder=(
        "e.g., Patient displays elevated blood glucose. "
        "Advised nutritional adjustments and scheduled a 2-week follow-up."
    )
)


# ==============================================================================
# PREPARE PDF DATA
# ==============================================================================

# Remove visual icons from the prediction title before adding it to the PDF.
clean_pdf_title = (
    status_title
    .replace("🟢 ", "")
    .replace("🟡 ", "")
    .replace("🚨 ", "")
)


# Convert values to appropriate numeric types.
pdf_age_val = int(age)
pdf_sys_val = int(systolic_bp)
pdf_dia_val = int(diastolic_bp)
pdf_bs_val = float(bs)
pdf_temp_val = float(body_temp)
pdf_hr_val = int(heart_rate)


# Create clean patient data for the PDF.
pdf_summary_data = {
    "Patient Age": f"{pdf_age_val} Years",
    "Systolic BP": f"{pdf_sys_val} mmHg",
    "Diastolic BP": f"{pdf_dia_val} mmHg",
    "Blood Sugar": f"{pdf_bs_val} mmol/L",
    "Body Temperature": f"{pdf_temp_val} F",
    "Heart Rate": f"{pdf_hr_val} BPM",
}


# ==============================================================================
# GENERATE PDF
# ==============================================================================

pdf_data = generate_pdf(
    patient_data=pdf_summary_data,
    probabilities=pred_probabilities,
    diagnosis=clean_pdf_title,
    notes=doctor_notes,
)


# ==============================================================================
# DOWNLOAD BUTTON
# ==============================================================================

st.download_button(
    label="Download Clinical PDF Report",
    data=pdf_data,
    file_name=f"maternal_health_report_{datetime.date.today()}.pdf",
    mime="application/pdf",
    use_container_width=True,
)
